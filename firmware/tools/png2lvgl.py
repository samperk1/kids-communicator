#!/usr/bin/env python3
"""PNG -> LVGL C sprite, packed by the COMPILER and not by this script.

🚨 THE RULE THIS TOOL EXISTS TO OBEY, from art.c:143 —
   "NEVER HAND-PACK RGB565 FOR LVGL. THIS BUILD STORES IT BYTE-SWAPPED."
The album-art decoder learned it the hard way: hand-packed pixels came out green
and magenta with a perfectly correct SHAPE, which looks like an art mistake and
is not. `CONFIG_LV_COLOR_16_SWAP=y` (sdkconfig:2496).

The first version of THIS tool made the same mistake: it emitted 0xE0,0x07 for
chroma green where the swapped build wants 0x07,0xE0. So it does not emit bytes
at all any more. It emits `LV_COLOR_MAKE(r, g, b)` initialisers into an
`lv_color_t[]`, and LVGL's own macro — which has a separate definition for
LV_COLOR_16_SWAP == 0 and == 1 (lv_color.h:150 vs :153) — does the packing at
COMPILE time. Change the colour depth or the swap setting and the sprites follow
automatically, with no regeneration.

Transparency is `LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED` on pure green #00FF00
(`CONFIG_LV_COLOR_CHROMA_KEY_HEX=0x00FF00`). PNG alpha below 50% becomes chroma.
⚠️ Opaque #00FF00 in the art would punch a hole, so it is a hard error.

Output is `const` -> lives in flash, costs zero RAM.

    ./png2lvgl.py art/flamingo1.png main/sprites/flamingo1.c
"""
import sys, os
from PIL import Image

CHROMA = (0, 255, 0)

def convert(png, name):
    im = Image.open(png).convert("RGBA")
    w, h = im.size
    px = im.load()
    cells, bad = [], 0
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 128:
                r, g, b = CHROMA
            elif (r, g, b) == CHROMA:
                bad += 1
            cells.append(f"LV_COLOR_MAKE(0x{r:02x},0x{g:02x},0x{b:02x})")
    if bad:
        sys.exit(f"ERROR: {png} has {bad} opaque pixels at exactly #00FF00, "
                 f"which is the transparent colour — they would punch holes in "
                 f"the sprite. Shift them a shade.")
    rows = [",\n".join("    " + ", ".join(cells[y * w:(y + 1) * w])
                       for y in range(h))]
    return f"""/* GENERATED by tools/png2lvgl.py from {os.path.basename(png)} — do not hand-edit.
 * Edit art/sprites.py (ASCII grids) and re-run it instead.
 *
 * {w}x{h}, {w*h} px, {w*h*2} bytes of flash at 16bpp. `const`, so no RAM.
 * Packed by LV_COLOR_MAKE at compile time, so LV_COLOR_16_SWAP is handled for
 * us — see the header of the generator before changing anything here. */
#include "lvgl.h"

static const lv_color_t {name}_px[] = {{
{rows[0]}
}};

const lv_img_dsc_t {name} = {{
    .header.cf          = LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED,
    .header.always_zero = 0,
    .header.w           = {w},
    .header.h           = {h},
    .data_size          = sizeof({name}_px),
    .data               = (const uint8_t *){name}_px,
}};
"""

if __name__ == "__main__":
    src, dst = sys.argv[1], sys.argv[2]
    nm = os.path.splitext(os.path.basename(src))[0]
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    open(dst, "w").write(convert(src, nm))
    print(f"{src} -> {dst}")
